static void mldsa44_kat(struct crypto_sig *tfm)
{
	size_t i;
	int ret;

	printk(KERN_INFO "Begin ML-DSA-44 tests\n");

	for (i = 0; i < ARRAY_SIZE(mldsa44_verif_vec); i++) {
		ret = mldsa_set_pub_key(tfm,
					mldsa44_verif_vec[i].pk,
					sizeof(mldsa44_verif_vec[i].pk));
		if (ret)
			printk(KERN_INFO "ERROR: Could not set public key!\n");
		ret = mldsa_verify(tfm,
				   mldsa44_verif_vec[i].sig,
				   sizeof(mldsa44_verif_vec[i].sig),
				   NULL, 0, NULL,
				   mldsa44_verif_vec[i].m,
				   sizeof(mldsa44_verif_vec[i].m),
				   NULL, 0);
		if (mldsa44_verif_vec[i].valid) {
			if (ret != 0)
				printk(KERN_INFO "ERROR: Could not verify signature!\n");
		} else {
			if (ret == 0)
				printk(KERN_INFO "ERROR: Could verify signature!\n");
		}
	}
	printk(KERN_INFO "End of ML-DSA-44 tests\n");
}
